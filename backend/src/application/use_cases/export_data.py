"""Use Case: Export Library, Playlists, and Settings to a Portable JSON Backup."""

from __future__ import annotations

from collections.abc import Callable
import logging
import os
from typing import Any, Optional

from ..dto import (
    BackupPlaylistDTO,
    BackupSettingsDTO,
    BackupTrackDTO,
    BackupTrackMetadataDTO,
    ExportBackupDTO,
)
from ...domain.entities import utc_now
from ...domain.repositories import IUnitOfWork

logger = logging.getLogger(__name__)

BACKUP_FORMAT_IDENTIFIER = "melosync-backup"
BACKUP_SCHEMA_VERSION = 1


class ExportBackupUseCase:
    """Exports application state (settings, tracks, metadata, playlists) into a portable backup bundle."""

    def __init__(self, uow_factory: Callable[[], IUnitOfWork]) -> None:
        self._uow_factory = uow_factory

    def execute(
        self,
        user_preferences: Optional[dict[str, Any]] = None,
        app_version: Optional[str] = None,
    ) -> ExportBackupDTO:
        version_str = app_version or os.getenv("MELOSYNC_BACKEND_VERSION", os.getenv("BACKEND_VERSION", "2.1.0"))

        with self._uow_factory() as uow:
            # 1. Fetch current settings
            settings_entity = uow.settings.get()
            backup_settings = BackupSettingsDTO(
                default_audio_quality=settings_entity.default_audio_quality.value,
                normalize_audio_lufs=settings_entity.normalize_audio_lufs,
                auto_tag_metadata=settings_entity.auto_tag_metadata,
                skip_non_music_sections=settings_entity.skip_non_music_sections,
                trim_silence=settings_entity.trim_silence,
                user_preferences=user_preferences or {},
            )

            # 2. Fetch tracks
            all_tracks = uow.tracks.list_all()
            backup_tracks: list[BackupTrackDTO] = []
            for t in all_tracks:
                meta_dto: Optional[BackupTrackMetadataDTO] = None
                if t.metadata:
                    meta_dto = BackupTrackMetadataDTO(
                        title=t.metadata.title,
                        artist=t.metadata.artist,
                        album=t.metadata.album,
                        year=t.metadata.year,
                        genre=t.metadata.genre,
                        track_number=t.metadata.track_number,
                        disc_number=t.metadata.disc_number,
                        cover_url=t.metadata.cover_url,
                        lyrics=t.metadata.lyrics,
                    )

                backup_tracks.append(
                    BackupTrackDTO(
                        youtube_id=t.youtube_id,
                        url=t.url,
                        original_title=t.original_title,
                        duration_seconds=t.duration_seconds,
                        channel_name=t.channel_name,
                        metadata=meta_dto,
                        play_count=t.play_count,
                        last_played_at_iso=t.last_played_at.isoformat() if t.last_played_at else None,
                    )
                )

            # 3. Fetch custom playlists
            all_playlists = uow.playlists.list_all()
            backup_playlists: list[BackupPlaylistDTO] = []
            for p in all_playlists:
                if p.playlist_type != "custom":
                    continue  # Smart playlists are dynamically regenerated by the system

                track_youtube_ids = [t.youtube_id for t in p.tracks if t.youtube_id]
                backup_playlists.append(
                    BackupPlaylistDTO(
                        name=p.name,
                        description=p.description or "",
                        cover_url=p.cover_url,
                        track_youtube_ids=track_youtube_ids,
                    )
                )

        return ExportBackupDTO(
            format=BACKUP_FORMAT_IDENTIFIER,
            version=BACKUP_SCHEMA_VERSION,
            exported_at_iso=utc_now().isoformat(),
            app_version=version_str,
            settings=backup_settings,
            tracks=backup_tracks,
            playlists=backup_playlists,
        )

